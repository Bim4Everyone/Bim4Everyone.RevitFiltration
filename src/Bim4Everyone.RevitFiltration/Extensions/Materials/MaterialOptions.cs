namespace Bim4Everyone.RevitFiltration.Extensions.Materials;

/// <summary>
///     Настройки отбора материалов по значениям их параметров.
/// </summary>
public sealed class MaterialOptions {
    /// <summary>
    ///     Допустимая погрешность для значений параметров с плавающей точкой.
    /// </summary>
    public double Tolerance { get; set; } = 1e-6;

    /// <summary>
    ///     Если True, инвертируется отбор материалов: подходящими считаются материалы,
    ///     которые не проходят заданные правила. По умолчанию False.
    ///     Инверсия строится по законам де Моргана:
    ///     "И" меняется на "ИЛИ" и наоборот, правило "больше" меняется на "меньше или равно" и т.д.
    ///     Проверка элемента при этом не меняется: элемент проходит фильтр,
    ///     если у него есть хотя бы один из отобранных материалов.
    ///     Пустые наборы правил не инвертируются.
    ///     Материалы, у которых нет параметра из правила, не попадают в отбор и при инверсии:
    ///     отсутствие параметра не отрицается.
    /// </summary>
    public bool Inverted { get; set; }
}
